#include <iostream>
using namespace std;

// Time Complexity: O(1) - Constant execution time for standard output operations.
// Space Complexity: O(1) - Constant memory allocated for char and double variables.

int main() {
    // Declare and initialize char and double variables
    char grade = 'A';
    double fee = 55000.75;

    // Display stored values
    cout << "Student Grade: " << grade << endl;
    cout << "Tuition Fee: $" << fee << endl;

    return 0;
}